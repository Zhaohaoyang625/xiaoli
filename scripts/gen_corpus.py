def main():
    ok, total_sec = 0, 0.0
    entries = []
    for i, text in enumerate(LINES, 1):
        pcm = tts_api.synthesize(text)
        if not pcm:
            print(f"[!!] 第{i}句合成失败：{text}", flush=True)
            continue
        # 防异常短音频（火山偶尔返空/截断）——<0.3s 视为坏数据
        sec = len(pcm) / 24000 / 2
        if sec < 0.3:
            print(f"[!!] 第{i}句过短 {sec:.1f}s，跳过", flush=True)
            continue
        fn = os.path.join(WAV_DIR, f"{i:03d}.wav")
        with wave.open(fn, "wb") as w:
            w.setnchannels(1)
            w.setsampwidth(2)
            w.setframerate(24000)
            w.writeframes(pcm)
        with open(os.path.join(WAV_DIR, f"{i:03d}.txt"), "w", encoding="utf-8") as f:
            f.write(text)
        entries.append(f"wavs/{i:03d}.wav|xiaoli|zh|{text}")
        ok += 1
        total_sec += sec
        print(f"[{i}/{len(LINES)}] {sec:.1f}s {text[:18]}", flush=True)
    with open(os.path.join(OUT, "list.txt"), "w", encoding="utf-8") as f:
        f.write("\n".join(entries) + "\n")
    print(f"[OK] 完成：{ok}/{len(LINES)} 句，总时长 {total_sec/60:.1f} 分钟", flush=True)
    print(f"[OK] 目录：{OUT}（list.txt 是 GPT-SoVITS 标注格式）", flush=True)


if __name__ == "__main__":
    main()
